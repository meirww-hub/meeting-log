package com.meirww.meetingscribe

/**
 * הופך רשומה מרשימת אנשי הקשר לשם דובר שאפשר לכתוב אותו בתוך משפט.
 *
 * אנשי הקשר בטלפון אינם "שמות" - הם רשומות ספר-טלפונים. בבדיקה על הרשימה
 * בפועל (1,477 רשומות): 334 מהן בנויות לפי המוסכמה `שם. תפקיד. חברה`, למשל
 * "דוד. פרוייקטים. קינג חשמלאי" או "Alex Aro. מתווך. אגמים". השם המלא הועתק
 * עד היום כלשונו לתווית הדובר, והסיכום יצא "דוד. פרוייקטים. קינג חשמלאי
 * אישר מול ניר כי..." - משפט שבור, עם נקודות שמפצלות אותו באמצע.
 *
 * הכלל: הסגמנט הראשון שאינו ריק לפני מפריד. הוא נגזר מהמוסכמה שהמשתמש עצמו
 * הקפיד עליה, ולא מניחוש איזה חלק "נשמע כמו שם" - ולכן הוא צפוי, ומה שלא
 * עונה עליו נשאר שלם ולא נחתך באמצע.
 */
object ContactName {

    /**
     * המפרידים שמופיעים בפועל ברשומות של המשתמש.
     *
     * נקודה נחשבת מפריד **רק כשאחריה רווח**. בלי התנאי הזה ראשי תיבות
     * נחתכים: "א.ד גורדון 1" היה הופך ל-"א". המוסכמה שהמשתמש כותב בה היא
     * תמיד "שם. תפקיד" עם רווח, אז התנאי לא מפספס כלום.
     */
    private val SEPARATOR = Regex("[.](?=\\s)|[|,،;]")

    /** נקודות/מפרידים שנשארו בקצה סגמנט אחרי הפיצול ("shlomi assulin.."). */
    private val EDGE_PUNCTUATION = Regex("^[.|,،;\\s]+|[.|,،;\\s]+$")

    /** אמוג'י, סמלים וסימני כיווניות בלתי-נראים - רעש בתווית של דובר. */
    private val NOISE = Regex(
        "[\\p{So}\\p{Cf}\\p{Co}\\x{1F000}-\\x{1FAFF}\\x{FE00}-\\x{FE0F}]"
    )

    private val WHITESPACE_RUN = Regex("\\s+")

    /** רשומה שכולה ספרות/סימני טלפון - איש קשר בלי שם אמיתי כלל. */
    private val NUMERIC_ONLY = Regex("^[\\d+\\-()*#\\s.]+$")

    /**
     * מחזיר שם קצר וקריא, או null אם ברשומה אין שם אמיתי (למשל רשומה
     * ששמה הוא מספר הטלפון עצמו) - ואז עדיף להישאר עם "הצד השני".
     */
    fun toSpeakerLabel(displayName: String?): String? {
        val cleaned = clean(displayName ?: return null) ?: return null

        // הסגמנט הראשון שאינו ריק: "דוד. פרוייקטים. קינג חשמלאי" -> "דוד".
        // "אינו ריק" ולא "הראשון" בגלל רשומות שמתחילות בנקודה (". אופק
        // Sahar Calizo") - שם הסגמנט הראשון ריק, והשם האמיתי הוא הבא אחריו.
        // סגמנט שכולו מספר מדולג גם הוא ("050-123-4567. משה אינסטלטור").
        return cleaned.split(SEPARATOR)
            .map { EDGE_PUNCTUATION.replace(it, "") }
            .firstOrNull { it.isNotEmpty() && !NUMERIC_ONLY.matches(it) }
            ?: cleaned
    }

    private fun clean(raw: String): String? {
        val text = WHITESPACE_RUN.replace(NOISE.replace(raw, " "), " ").trim()
        if (text.isEmpty() || NUMERIC_ONLY.matches(text)) return null
        return text
    }
}
