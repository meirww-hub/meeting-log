def _format_transcript(segments: list[TranscriptSegment]) -> str:
    return "\n".join(
        f"{s.speaker_label}{'' if s.speaker_confident else UNCERTAIN_HINT}: {s.text}"
        for s in segments
    )


_FIGURE_RE = re.compile(r"\d")


def _word_count(segments: list[TranscriptSegment]) -> int:
    """מילות הדיבור בלבד - בלי תוויות הדוברים, שהן רעש קבוע שגדל עם מספר
    הקטעים ולא עם כמות התוכן שנאמר."""
    return sum(len(s.text.split()) for s in segments)


def _figure_count(segments: list[TranscriptSegment]) -> int:
    """כמה מילים בתמלול מכילות ספרה - מדד לצפיפות הנתונים בשיחה.

    שתי שיחות באותו אורך יכולות להיות שונות לגמרי בכמות המידע הקונקרטי:
    ישיבת הנהלה עם עשרות סכומים ותאריכים צריכה יותר מקום מפטפוט באותו אורך,
    אחרת המספרים פשוט לא נכנסים לתקציב ונופלים."""
    return sum(1 for s in segments for w in s.text.split() if _FIGURE_RE.search(w))


def _summary_budget(word_count: int, figure_count: int) -> tuple[int, int]:
    """מחזיר (מינימום נושאים, מינימום מילים בסיכום) - שתי רצפות, לא תקרות.

    היעד מחושב בקוד ולא מושאר לשיקול המודל, כי מודלי שפה מתכנסים לאורך פלט
    קבוע כשלא נותנים להם מספר מפורש - הנחיה מילולית ("סכם באופן
    פרופורציונלי") מייצרת את אותו סיכום בן שלוש שורות גם לשיחה של דקתיים
    וגם לפגישה של שעתיים.

    הסקאלה תת-לינארית (שורש): שיחה ארוכה פי 10 מקבלת סיכום ארוך פי ~3 בלבד,
    כי יחס הדחיסה הטבעי גדל עם אורך השיחה - סיכום של 3,000 מילים מפספס את
    מטרתו. העקומה שנוצרת, לפי ~130 מילות דיבור לדקה בעברית ובהנחת צפיפות
    נתונים בינונית (~4% מהמילים מכילות ספרה):

       30 שנ'    ~65 מילים  →   2+ נושאים,    29+ מילים (חסום ע"י תקרת 45%)
        2 דק'   ~260 מילים  →   2+ נושאים,    90+ מילים
       10 דק' ~1,300 מילים  →   5+ נושאים,   314+ מילים
       30 דק' ~3,900 מילים  →   9+ נושאים,   771+ מילים
       60 דק' ~7,800 מילים  →  13+ נושאים, 1,391+ מילים

    ובאותו אורך (30 דק'), לפי צפיפות הנתונים בפועל: שיחה כמעט בלי מספרים
    מקבלת ~499 מילים, ושיחה עמוסת נתונים ~918. זה ההבדל שאורך לבדו מפספס.

    היעד הוא רצפה, לא תקרה (ראה _TASK_SCHEMA_HINT): עדיף סיכום ארוך מהיעד
    על פני סיכום שהשמיט נושא או נתון.
    """
    root = math.sqrt(max(word_count, 1))
    topics = min(max(round(root / 7), 2), 16)
    # גם העומק לכל נושא גדל, לא רק מספר הנושאים: בפגישה ארוכה כל נושא נדון
    # לעומק ומגיע לו יותר משפט אחד.
    words_per_topic = min(max(round(30 + root / 3), 35), 75)
    base = topics * words_per_topic
    # תוספת לפי צפיפות הנתונים. נמדד בבדיקה חיה מול Gemini: המודל מציית ליעד
    # המילים כמעט במדויק, ולכן יעד שנגזר מאורך בלבד הוא בדיוק מה שמפיל את
    # המספרים - בישיבה עם 55 נתונים ב-1,069 מילים שרדו רק 27% מהם, כי פשוט
    # לא היה להם מקום. עם התוספת הזו (ועם ניסוח הרצפה בפרומפט) השרידות עלתה
    # ל-80% בלי אף מספר מומצא. המקדם 2 ולא יותר כדי שהתוספת תבדיל בין
    # צפיפויות לאורך כל הטווח במקום להיחסם מיד בתקרה.
    figures_bonus = min(figure_count * 2, base)
    # תקרת ביטחון להקלטות זעירות: בלי זה הקלטה של חצי דקה (~65 מילים) מקבלת
    # יעד ארוך מהתמלול עצמו, שהוא הזמנה לריפוד ולהמצאת פרטים.
    summary_words = min(base + figures_bonus, max(round(word_count * 0.45), 25))
    return topics, summary_words


def summarize_and_extract_todos(
    segments: list[TranscriptSegment], today_iso: str
) -> tuple[str, str, list[TodoItem], dict[str, str]]:
    """מחזיר (כותרת מוצעת, סיכום, TO DO, מיפוי תוויות-דובר->שם אמיתי). הכותרת
    המוצעת משמשת רק כשהמשתמש לא הזין כותרת משלו (ראה pipeline.py). מיפוי
    השמות משמש להחלפת תוויות גנריות ("דובר 1"/"הצד השני") בשם האמיתי שהוזכר
    בתוך השיחה עצמה - ראה pipeline._apply_speaker_names."""
    client = genai.Client(api_key=settings.gemini_api_key)

    transcript_text = _format_transcript(segments)
    word_count = _word_count(segments)
    figure_count = _figure_count(segments)
    min_topics, min_words = _summary_budget(word_count, figure_count)

    # ההסבר על סימון אי-הוודאות נכנס רק כשיש בתמלול שורות מסומנות. פרומפט
    # ארוך יותר עולה במחיר ובקשב, וכלל שאין לו אף מקרה בתמלול הוא רעש נטו.
    uncertainty_rule = (
        _UNCERTAINTY_RULE.format(hint=UNCERTAIN_HINT.strip(), unknown=UNKNOWN_SPEAKER)
        if any(not s.speaker_confident for s in segments)
        else ""
    )

    task_hint = _TASK_SCHEMA_HINT.format(
        today=today_iso,
        word_count=word_count,
        figure_count=figure_count,
        min_topics=min_topics,
        min_words=min_words,
        uncertainty_rule=uncertainty_rule,
    )

    response = call_with_retry(
        client.models.generate_content,
        model=_MODEL,
        contents=f"{task_hint}\n\nתמלול הפגישה:\n{transcript_text}",
        config=types.GenerateContentConfig(
            system_instruction=_SYSTEM_PROMPT,
            response_mime_type="application/json",
            response_schema=_MeetingSummary,
            # מפורש, מאותה סיבה בדיוק שבתמלול (ראה transcription.py): בלי
            # התקרה המפורשת ה-API חותך את הפלט הרבה לפני יכולת המודל, וסיכום
            # ארוך - שהוא בדיוק מה שפגישה ארוכה מקבלת - חוזר כ-JSON קטוע.
            max_output_tokens=_MAX_OUTPUT_TOKENS,
        ),
    )

    # result.parsed הוא כבר מופע _MeetingSummary מאומת (Pydantic), לא dict/JSON
    # גולמי - כך שאי-התאמה בין הסכמה (list) לקוד שקורא אותה (שהניח dict,
    # וקרס עם "'list' object has no attribute 'items'" על כל הקלטה עם שם
    # דובר אמיתי) הופכת לבלתי-אפשרית structurally במקום להתגלות רק בזמן ריצה.
    parsed: _MeetingSummary = response.parsed or _MeetingSummary.model_validate_json(
        response.text
    )

    # רשת ביטחון לניסוח חוסר-הוודאות: מקומו בגוף הסיכום בלבד. בעמודת
    # "אחראי" שבגיליון המשימות הוא לא שווה כלום - "אחד הדוברים" אינו אדם
    # שאפשר להטיל עליו משימה - ולכן משימה כזו חוזרת להיות חסרת אחראי, כמו
    # כל משימה שלא ידוע מי יבצע. באותו אופן הוא לא רשאי להיכנס למיפוי שמות
    # הדוברים, שממנו נבנית רשימת הדוברים במסך "עריכת דוברים".
    for todo in parsed.todos:
        if todo.owner and todo.owner.strip() == UNKNOWN_SPEAKER:
            todo.owner = None

    speaker_names = {
        sn.label: sn.name.strip()
        for sn in parsed.speaker_names
        if sn.label != "אני"
        and sn.name.strip()
        and UNKNOWN_SPEAKER not in (sn.label, sn.name.strip())
    }

    return parsed.title, parsed.summary, parsed.todos, speaker_names
