from app.models import TranscriptSegment


def _segs(pairs: list[tuple[str, str]]) -> list[TranscriptSegment]:
    out, t = [], 0.0
    for spk, text in pairs:
        dur = max(len(text.split()) / 2.2, 1.0)
        out.append(
            TranscriptSegment(
                speaker_label=spk,
                speaker_tag=1 if spk == "אני" else 2,
                text=text,
                start_seconds=t,
                end_seconds=t + dur,
            )
        )
        t += dur
    return out


